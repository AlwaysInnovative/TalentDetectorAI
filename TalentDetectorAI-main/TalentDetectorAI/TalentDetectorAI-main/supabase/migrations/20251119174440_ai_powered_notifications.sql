-- Enhanced notifications with AI recommendations
ALTER TABLE notifications
ADD COLUMN IF NOT EXISTS action_type TEXT,
ADD COLUMN IF NOT EXISTS action_data JSONB,
ADD COLUMN IF NOT EXISTS ai_priority TEXT DEFAULT 'normal',
ADD COLUMN IF NOT EXISTS auto_action_taken BOOLEAN DEFAULT FALSE,
ADD COLUMN IF NOT EXISTS expires_at TIMESTAMPTZ;

-- AI-powered trigger: Auto-generate RTR when CV uploaded
CREATE OR REPLACE FUNCTION ai_auto_generate_rtr()
RETURNS TRIGGER AS $$
DECLARE
  agency_record RECORD;
  candidate_record RECORD;
  job_record RECORD;
BEGIN
  -- Only trigger if CV just uploaded and RTR doesn't exist
  IF NEW.cv_url IS NOT NULL AND OLD.cv_url IS NULL AND NEW.right_to_represent_url IS NULL THEN
    
    -- Get all relevant data
    SELECT * INTO agency_record FROM profiles WHERE id = NEW.agency_id;
    SELECT * INTO candidate_record FROM candidates WHERE id = NEW.candidate_id;
    SELECT * INTO job_record FROM jobs WHERE id = NEW.job_id;

    -- Generate RTR document content
    DECLARE
      rtr_content TEXT;
      file_path TEXT;
    BEGIN
      rtr_content := format(E'RIGHT TO REPRESENT AGREEMENT\n\n' ||
        'Date: %s\n\n' ||
        'AGENCY: %s\n' ||
        'CANDIDATE: %s\n' ||
        'EMAIL: %s\n' ||
        'POSITION: %s\n\n' ||
        'This agreement grants exclusive representation rights for 90 days.\n\n' ||
        '1. REPRESENTATION SCOPE\n' ||
        '   - Agency may submit candidate materials to hiring company\n' ||
        '   - Agency serves as intermediary for all communications\n' ||
        '   - Candidate agrees not to apply directly during representation period\n\n' ||
        '2. AI MATCH ANALYSIS\n' ||
        '   - Match Score: %s%%\n' ||
        '   - AI recommends proceeding with this placement\n\n' ||
        'Generated automatically by TalentDetector AI\n' ||
        'Document ID: %s\n' ||
        'Timestamp: %s',
        NOW()::date,
        agency_record.full_name,
        candidate_record.name,
        candidate_record.email,
        job_record.title,
        COALESCE(NEW.ai_match_score, 0),
        NEW.id,
        NOW()
      );

      file_path := 'rtr_auto_' || NEW.id || '_' || extract(epoch from NOW())::bigint || '.txt';

      -- Note: In production, this would call storage API
      -- For now, we'll set a placeholder and queue for generation
      
      UPDATE candidate_interests
      SET 
        right_to_represent_url = 'pending_generation',
        agency_notes = 'RTR auto-generated by AI - awaiting storage upload'
      WHERE id = NEW.id;

    END;

    -- Notify candidate to sign RTR
    INSERT INTO notifications (user_id, type, title, message, link, action_type, action_data, ai_priority, metadata)
    VALUES (
      candidate_record.user_id,
      'rtr_ready_for_signature',
      '🤖 AI Generated: Document Ready to Sign',
      'Your Right-to-Represent agreement has been automatically generated and is ready for your signature',
      '/dashboard/candidate/interests/' || NEW.id,
      'sign_document',
      jsonb_build_object('interest_id', NEW.id, 'document_type', 'rtr'),
      'high',
      jsonb_build_object('ai_generated', true, 'match_score', NEW.ai_match_score)
    );

    -- Notify agency that RTR was auto-generated
    INSERT INTO notifications (user_id, type, title, message, link, action_type, ai_priority, metadata)
    VALUES (
      NEW.agency_id,
      'rtr_auto_generated',
      '🤖 AI Action: RTR Auto-Generated',
      candidate_record.name || ' uploaded CV. RTR automatically generated and sent for signature',
      '/dashboard/agency/interests',
      'view_interest',
      'normal',
      jsonb_build_object('interest_id', NEW.id, 'candidate_id', NEW.candidate_id, 'ai_action', true)
    );

  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_ai_auto_generate_rtr ON candidate_interests;
CREATE TRIGGER trigger_ai_auto_generate_rtr
AFTER UPDATE OF cv_url ON candidate_interests
FOR EACH ROW
EXECUTE FUNCTION ai_auto_generate_rtr();

-- Enhanced CV upload notification with AI insights
CREATE OR REPLACE FUNCTION notify_cv_uploaded_enhanced()
RETURNS TRIGGER AS $$
DECLARE
  interest RECORD;
  ai_recommendation TEXT;
BEGIN
  IF NEW.cv_url IS NOT NULL AND OLD.cv_url IS NULL THEN
    SELECT * INTO interest FROM candidate_interests WHERE id = NEW.id;
    
    -- Generate AI recommendation
    IF NEW.ai_match_score >= 85 THEN
      ai_recommendation := '🌟 HIGHLY RECOMMENDED: Excellent match. Fast-track to interview.';
    ELSIF NEW.ai_match_score >= 75 THEN
      ai_recommendation := '✅ RECOMMENDED: Strong candidate. Schedule screening call.';
    ELSIF NEW.ai_match_score >= 60 THEN
      ai_recommendation := '👍 GOOD FIT: Consider for next steps.';
    ELSE
      ai_recommendation := '⚠️ REVIEW NEEDED: May need additional evaluation.';
    END IF;
    
    -- Notify agency with AI insights
    INSERT INTO notifications (user_id, type, title, message, link, action_type, action_data, ai_priority, metadata)
    VALUES (
      interest.agency_id,
      'cv_uploaded_ai_analysis',
      '🎯 CV Received: ' || NEW.ai_match_score || '% Match',
      'AI Analysis Complete: ' || ai_recommendation,
      '/dashboard/agency/interests',
      'review_cv',
      jsonb_build_object(
        'interest_id', NEW.id,
        'cv_url', NEW.cv_url,
        'match_score', NEW.ai_match_score,
        'quick_actions', ARRAY['download_cv', 'generate_rtr', 'contact_candidate']
      ),
      CASE 
        WHEN NEW.ai_match_score >= 85 THEN 'urgent'
        WHEN NEW.ai_match_score >= 75 THEN 'high'
        ELSE 'normal'
      END,
      jsonb_build_object(
        'candidate_id', interest.candidate_id,
        'job_id', interest.job_id,
        'ai_analysis', NEW.ai_cv_analysis,
        'recommendation', ai_recommendation
      )
    );

    -- Notify hiring manager with AI summary
    INSERT INTO notifications (user_id, type, title, message, link, action_type, ai_priority, metadata)
    SELECT 
      j.manager_id,
      'candidate_cv_submitted',
      '📋 New Application: ' || NEW.ai_match_score || '% Match',
      'AI recommends: ' || ai_recommendation,
      '/dashboard/manager/jobs/' || j.id,
      'review_application',
      CASE WHEN NEW.ai_match_score >= 85 THEN 'high' ELSE 'normal' END,
      jsonb_build_object(
        'interest_id', NEW.id,
        'match_score', NEW.ai_match_score,
        'agency_id', interest.agency_id
      )
    FROM jobs j
    WHERE j.id = interest.job_id;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_notify_cv_uploaded_enhanced ON candidate_interests;
CREATE TRIGGER trigger_notify_cv_uploaded_enhanced
AFTER UPDATE OF cv_url ON candidate_interests
FOR EACH ROW
EXECUTE FUNCTION notify_cv_uploaded_enhanced();

-- AI-powered response notification
CREATE OR REPLACE FUNCTION notify_candidate_response_ai()
RETURNS TRIGGER AS $$
DECLARE
  interest RECORD;
  ai_next_step TEXT;
BEGIN
  IF OLD.status != NEW.status THEN
    SELECT * INTO interest FROM candidate_interests WHERE id = NEW.id;
    
    -- AI determines next step
    IF NEW.status = 'interested' AND NEW.ai_match_score >= 80 THEN
      ai_next_step := 'Schedule interview within 48 hours';
    ELSIF NEW.status = 'interested' THEN
      ai_next_step := 'Arrange screening call within 5 days';
    ELSIF NEW.status = 'need_more_info' THEN
      ai_next_step := 'Respond to candidate questions within 24 hours';
    ELSE
      ai_next_step := 'Thank candidate and close application';
    END IF;

    -- Notify agency with AI next steps
    INSERT INTO notifications (user_id, type, title, message, link, action_type, action_data, ai_priority, metadata)
    VALUES (
      NEW.agency_id,
      'candidate_responded_ai',
      '💬 Response: ' || INITCAP(NEW.status),
      'AI Next Step: ' || ai_next_step,
      '/dashboard/agency/interests',
      'take_action',
      jsonb_build_object(
        'interest_id', NEW.id,
        'suggested_action', ai_next_step,
        'quick_actions', ARRAY['schedule_interview', 'send_message', 'update_status']
      ),
      CASE 
        WHEN NEW.status = 'interested' AND NEW.ai_match_score >= 80 THEN 'urgent'
        WHEN NEW.status = 'interested' THEN 'high'
        ELSE 'normal'
      END,
      jsonb_build_object(
        'candidate_id', interest.candidate_id,
        'response_type', NEW.status,
        'ai_next_step', ai_next_step
      )
    );

    -- Notify manager
    INSERT INTO notifications (user_id, type, title, message, link, ai_priority, metadata)
    SELECT 
      j.manager_id,
      'candidate_response_update',
      '📊 Application Update: ' || INITCAP(NEW.status),
      'Candidate response received. AI recommends: ' || ai_next_step,
      '/dashboard/manager/applications',
      CASE WHEN NEW.status = 'interested' THEN 'high' ELSE 'normal' END,
      jsonb_build_object('interest_id', NEW.id, 'ai_recommendation', ai_next_step)
    FROM jobs j
    WHERE j.id = interest.job_id;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_notify_candidate_response_ai ON candidate_interests;
CREATE TRIGGER trigger_notify_candidate_response_ai
AFTER UPDATE OF status ON candidate_interests
FOR EACH ROW
EXECUTE FUNCTION notify_candidate_response_ai();


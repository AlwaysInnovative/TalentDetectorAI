import { createClient } from '@supabase/supabase-js'
import { NextResponse } from 'next/server'

export async function POST(request: Request) {
  try {
    const body = await request.json()
    const { interestId } = body

    if (!interestId) {
      return NextResponse.json(
        { error: 'Interest ID required' },
        { status: 400 }
      )
    }

    const supabaseAdmin = createClient(
      process.env.NEXT_PUBLIC_SUPABASE_URL!,
      process.env.SUPABASE_SERVICE_ROLE_KEY!
    )

    // Get full interest data with correct column names
    const { data: interest, error: fetchError } = await supabaseAdmin
      .from('candidate_interests')
      .select(`
        *,
        candidates(id, name, email, phone, location, user_id),
        jobs(id, title, location, salary_min, salary_max, employment_type, description),
        profiles!candidate_interests_agency_id_fkey(id, full_name, company, email, phone)
      `)
      .eq('id', interestId)
      .single()

    if (fetchError) {
      console.error('Fetch error:', fetchError)
      throw new Error(`Failed to fetch interest: ${fetchError.message}`)
    }

    if (!interest) {
      throw new Error('Interest not found')
    }

    console.log('Interest data:', interest)

    const candidate = interest.candidates
    const job = interest.jobs
    const agency = interest.profiles

    if (!candidate || !job || !agency) {
      throw new Error('Missing related data')
    }

    // Generate RTR content
    const rtrContent = generateRTRDocument({
      candidate,
      job,
      agency,
      interest,
      generatedDate: new Date(),
      matchScore: interest.ai_match_score || 0,
      aiAnalysis: interest.ai_cv_analysis
    })

    // Upload to storage
    const fileName = `rtr_${interestId}_${Date.now()}.txt`
    const { error: uploadError } = await supabaseAdmin.storage
      .from('documents')
      .upload(fileName, rtrContent, {
        contentType: 'text/plain',
        upsert: false
      })

    if (uploadError) {
      console.error('Upload error:', uploadError)
      throw new Error(`Storage upload failed: ${uploadError.message}`)
    }

    const { data: { publicUrl } } = supabaseAdmin.storage
      .from('documents')
      .getPublicUrl(fileName)

    console.log('RTR uploaded to:', publicUrl)

    // Update interest with RTR URL
    const { error: updateError } = await supabaseAdmin
      .from('candidate_interests')
      .update({
        right_to_represent_url: publicUrl,
        agency_notes: `RTR auto-generated by AI on ${new Date().toISOString()}`
      })
      .eq('id', interestId)

    if (updateError) {
      console.error('Update error:', updateError)
      throw new Error(`Failed to update interest: ${updateError.message}`)
    }

    // Create document record
    await supabaseAdmin.from('interest_documents').insert({
      interest_id: interestId,
      document_type: 'right_to_represent',
      file_url: publicUrl,
      filename: fileName,
      metadata: {
        auto_generated: true,
        ai_powered: true,
        match_score: interest.ai_match_score,
        generated_at: new Date().toISOString()
      }
    })

    // Notify candidate to sign (use candidate's user_id)
    if (candidate.user_id) {
      console.log('Notifying candidate:', candidate.user_id)
      
      await supabaseAdmin.from('notifications').insert({
        user_id: candidate.user_id,
        type: 'rtr_ready_signature',
        title: '✍️ E-Signature Required',
        message: `Your Right-to-Represent agreement for "${job.title}" is ready. Click to review and sign.`,
        link: `/dashboard/candidate/interests/${interestId}/sign-rtr`,
        action_type: 'sign_document',
        action_data: {
          interest_id: interestId,
          document_url: publicUrl,
          document_type: 'rtr'
        },
        ai_priority: 'high',
        metadata: {
          ai_generated: true,
          requires_signature: true,
          interest_id: interestId,
          job_title: job.title
        }
      })

      console.log('Candidate notification sent')
    } else {
      console.warn('Candidate has no user_id, cannot send notification')
    }

    // Notify agency
    await supabaseAdmin.from('notifications').insert({
      user_id: interest.agency_id,
      type: 'rtr_sent_for_signature',
      title: '📄 RTR Sent to Candidate',
      message: `${candidate.name} has been sent the Right-to-Represent agreement for signature`,
      link: `/dashboard/agency/interests`,
      ai_priority: 'normal',
      metadata: {
        interest_id: interestId,
        candidate_id: interest.candidate_id,
        candidate_name: candidate.name
      }
    })

    console.log('Agency notification sent')

    return NextResponse.json({
      success: true,
      rtr_url: publicUrl,
      message: 'RTR generated and sent to candidate for signature',
      candidate_notified: !!candidate.user_id
    })

  } catch (error: any) {
    console.error('RTR generation error:', error)
    return NextResponse.json(
      { error: error.message || 'Failed to generate RTR' },
      { status: 500 }
    )
  }
}


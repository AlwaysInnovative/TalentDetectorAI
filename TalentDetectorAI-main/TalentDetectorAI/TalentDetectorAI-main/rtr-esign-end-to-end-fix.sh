'use client'
import { useRef, useState, useEffect } from 'react'
import { createClient } from '@/lib/supabase/client'
import { useRouter } from 'next/navigation'
import toast from 'react-hot-toast'
import Link from 'next/link'
import { Loader2, ArrowLeft, CheckCircle, Trash2 } from 'lucide-react'

export default function CandidateSignRTR({ params }) {
  const router = useRouter()
  const canvasRef = useRef(null)
  const [interest, setInterest] = useState(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')
  const [drawing, setDrawing] = useState(false)
  const [signed, setSigned] = useState(false)
  const [submitting, setSubmitting] = useState(false)

  useEffect(() => {
    async function fetchInterest() {
      try {
        setLoading(true)
        const supabase = createClient()
        const { data: { user } } = await supabase.auth.getUser()
        if (!user) throw new Error('Not logged in')
        const { data: candidate } = await supabase
          .from('candidates')
          .select('id')
          .eq('user_id', user.id)
          .single()
        if (!candidate) throw new Error('Candidate not found')
        const { data, error } = await supabase
          .from('candidate_interests')
          .select('*, jobs(id, title)')
          .eq('id', params.id)
          .eq('candidate_id', candidate.id)
          .single()
        if (error || !data) throw new Error('Opportunity not found')
        setInterest(data)
      } catch (err) {
        setError(err.message)
      } finally {
        setLoading(false)
      }
    }
    fetchInterest()
  }, [params.id])

  useEffect(() => {
    const canvas = canvasRef.current
    if (!canvas) return
    canvas.width = canvas.offsetWidth
    canvas.height = 130
    const ctx = canvas.getContext('2d')
    if (!ctx) return
    ctx.lineWidth = 2
    ctx.lineCap = 'round'
    ctx.strokeStyle = '#000'
  }, [loading])

  function getCoords(e) {
    const canvas = canvasRef.current
    const rect = canvas.getBoundingClientRect()
    return e.touches
      ? { x: e.touches[0].clientX - rect.left, y: e.touches[0].clientY - rect.top }
      : { x: e.clientX - rect.left, y: e.clientY - rect.top }
  }

  function startDrawing(e) {
    setDrawing(true)
    setSigned(true)
    draw(e)
  }
  function draw(e) {
    if (!drawing) return
    const canvas = canvasRef.current
    const ctx = canvas.getContext('2d')
    const { x, y } = getCoords(e)
    ctx.lineTo(x, y)
    ctx.stroke()
  }
  function stopDrawing() {
    setDrawing(false)
    const canvas = canvasRef.current
    const ctx = canvas.getContext('2d')
    ctx.beginPath()
  }
  function clearSignature() {
    const canvas = canvasRef.current
    canvas.getContext('2d').clearRect(0, 0, canvas.width, canvas.height)
    setSigned(false)
  }
  async function submitSignature() {
    if (!signed) { toast.error('Please sign before submitting.'); return; }
    setSubmitting(true)
    try {
      const canvas = canvasRef.current
      const imageData = canvas.toDataURL('image/png')
      const resp = await fetch('/api/sign-rtr', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ interestId: params.id, signature: imageData })
      })
      if (!resp.ok) { const err = await resp.json(); throw new Error(err.error || 'Failed to submit signature') }
      toast.success('Signed and submitted!')
      setTimeout(() => router.push(`/dashboard/candidate/interests/${params.id}`), 1500)
    } catch (err) {
      toast.error(err.message)
    } finally {
      setSubmitting(false)
    }
  }

  if (loading) return <div className="flex items-center justify-center min-h-screen"><Loader2 className="w-12 h-12 animate-spin text-blue-600"/></div>

  if (error) return <div className="text-red-600 font-bold text-xl flex flex-col items-center justify-center min-h-screen"><p>{error}</p><Link href="/dashboard/candidate"><a className="text-blue-600 underline mt-4">Back to Dashboard</a></Link></div>

  return (
    <div className="p-8 max-w-xl mx-auto bg-white rounded-xl shadow">
      <Link href={`/dashboard/candidate/interests/${params.id}`}>
        <button className="mb-6 text-blue-600 hover:underline flex items-center gap-2"><ArrowLeft className="w-5 h-5"/> Back</button>
      </Link>
      <h1 className="text-2xl font-bold mb-4">{interest.jobs.title} - Sign RTR</h1>
      <iframe src={interest.right_to_represent_url} className="w-full h-60 mb-4 border rounded" title="RTR Doc"/>
      <canvas
        ref={canvasRef}
        className="border rounded w-full h-28 bg-white"
        onPointerDown={startDrawing}
        onPointerMove={draw}
        onPointerUp={stopDrawing}
        onPointerLeave={stopDrawing}
        />
      <div className="mt-3 flex gap-4">
        <button onClick={clearSignature} className="py-2 bg-gray-200 rounded flex-1 flex gap-2 justify-center items-center"><Trash2 className="w-5 h-5"/>Clear</button>
        <button onClick={submitSignature} disabled={submitting || !signed} className="py-2 bg-blue-600 text-white rounded flex-1">{submitting ? "Signing..." : "Sign & Submit"}</button>
      </div>
      <p className="mt-4 text-gray-600 text-xs italic">Electronic signature is legally binding.</p>
    </div>
  )
}

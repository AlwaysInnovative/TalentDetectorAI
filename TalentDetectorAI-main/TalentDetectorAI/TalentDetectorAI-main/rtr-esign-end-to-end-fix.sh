import { createClient } from '@supabase/supabase-js'
import { NextResponse } from 'next/server'
export const dynamic = 'force-dynamic'

export async function POST(request) {
  try {
    const { interestId, signature } = await request.json()
    if (!interestId || !signature) return NextResponse.json({ error:'Missing params' }, { status:400 })

    const supabaseAdmin = createClient(
      process.env.NEXT_PUBLIC_SUPABASE_URL!,
      process.env.SUPABASE_SERVICE_ROLE_KEY!
    )

    const { data: interest, error } = await supabaseAdmin
      .from('candidate_interests')
      .select('*, candidates(name, user_id), jobs(title), agency_id')
      .eq('id', interestId)
      .single()
    if (error || !interest) return NextResponse.json({ error:'Interest not found' }, {status:404})

    const base64 = signature.replace(/^data:image\/png;base64,/, '')
    const buf = Buffer.from(base64, 'base64')
    const fname = `signature_${interestId}_${Date.now()}.png`
    const { error: uploadError } = await supabaseAdmin.storage
      .from('documents')
      .upload(fname, buf, { contentType:'image/png' })
    if (uploadError) return NextResponse.json({ error:uploadError.message }, {status:500})

    const { data: { publicUrl } } = supabaseAdmin.storage.from('documents').getPublicUrl(fname)

    await supabaseAdmin.from('candidate_interests').update({
      right_to_represent_signed: true,
      right_to_represent_signed_at: new Date().toISOString(),
      candidate_signature_url: publicUrl
    }).eq('id', interestId)

    await supabaseAdmin.from('notifications').insert({
      user_id: interest.agency_id,
      type: 'rtr_signed',
      title: 'RTR signed by candidate',
      message: `${interest.candidates.name} signed RTR for ${interest.jobs.title}`,
      link: `/dashboard/agency/interests/${interestId}`,
      ai_priority:'high',
      metadata:{ interest_id: interestId, signature_url: publicUrl }
    })

    return NextResponse.json({ success: true, message: 'Signature saved.' })
  } catch (err) {
    return NextResponse.json({ error: err.message || 'Failed to save signature' }, { status:500 })
  }
}

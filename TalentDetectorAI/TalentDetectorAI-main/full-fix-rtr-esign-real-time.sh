'use client'
import { useState, useEffect, useRef } from 'react'
import { createClient } from '@/lib/supabase/client'
import Link from 'next/link'
import { Loader2, ArrowLeft, CheckCircle, Trash2, Download } from 'lucide-react'
import toast from 'react-hot-toast'
import { useRouter } from 'next/navigation'

export default function SignRTRPage({ params }) {
  const [loading, setLoading] = useState(true)
  const [signing, setSigning] = useState(false)
  const [interest, setInterest] = useState(null)
  const [error, setError] = useState('')
  const canvasRef = useRef(null)
  const [drawing, setDrawing] = useState(false)
  const [hasSignature, setHasSignature] = useState(false)
  const router = useRouter()

  useEffect(() => {
    async function load() {
      try {
        setLoading(true)
        const supabase = createClient()
        const { data: { user } } = await supabase.auth.getUser()
        if (!user) throw new Error('Not logged in')

        const { data: candidate } = await supabase
          .from('candidates')
          .select('id')
          .eq('user_id', user.id)
          .single()

        if (!candidate) throw new Error('Candidate not found')

        const { data, error } = await supabase
          .from('candidate_interests')
          .select('*, jobs(id, title), candidates(name)')
          .eq('id', params.id)
          .eq('candidate_id', candidate.id)
          .single()

        if (error || !data) throw new Error('Opportunity not found')

        setInterest(data)
      } catch (e) {
        setError(e.message)
      } finally {
        setLoading(false)
      }
    }
    load()
  }, [params.id])

  useEffect(() => {
    const canvas = canvasRef.current
    if (!canvas) return

    canvas.width = canvas.offsetWidth
    canvas.height = 150

    const ctx = canvas.getContext('2d')
    if (!ctx) return

    ctx.lineWidth = 2
    ctx.lineCap = 'round'
    ctx.strokeStyle = '#000'
  }, [loading])

  function getCoords(e) {
    const canvas = canvasRef.current
    const rect = canvas.getBoundingClientRect()
    if (e.touches) {
      return {x: e.touches[0].clientX - rect.left, y: e.touches[0].clientY - rect.top}
    } else {
      return {x: e.clientX - rect.left, y: e.clientY - rect.top}
    }
  }

  function startDrawing(e) {
    const canvas = canvasRef.current
    const ctx = canvas.getContext('2d')
    const { x, y } = getCoords(e)
    ctx.beginPath()
    ctx.moveTo(x, y)
    setDrawing(true)
    setHasSignature(true)
  }
  function draw(e) {
    if (!drawing) return
    const canvas = canvasRef.current
    const ctx = canvas.getContext('2d')
    const { x, y } = getCoords(e)
    ctx.lineTo(x, y)
    ctx.stroke()
  }
  function stopDrawing() {
    setDrawing(false)
  }
  function clearCanvas() {
    const canvas = canvasRef.current
    const ctx = canvas.getContext('2d')
    ctx.clearRect(0, 0, canvas.width, canvas.height)
    setHasSignature(false)
  }
  async function submitSignature() {
    if (!hasSignature) {
      toast.error('Please provide your signature')
      return
    }
    setSigning(true)
    try {
      const canvas = canvasRef.current
      const dataUrl = canvas.toDataURL('image/png')

      const response = await fetch('/api/sign-rtr', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ interestId: params.id, signature: dataUrl })
      })

      const result = await response.json()
      if (!response.ok) throw new Error(result.error || 'Failed to submit signature')

      toast.success('RTR signed successfully!')

      setTimeout(() => router.push(`/dashboard/candidate/interests/${params.id}`), 1500)
    } catch (error) {
      toast.error(error.message)
    } finally {
      setSigning(false)
    }
  }

  if (loading) return <div className="min-h-screen flex justify-center items-center p-12"><Loader2 className="w-16 h-16 text-blue-600 animate-spin"/></div>
  if (error) return (
    <div className="min-h-screen flex flex-col justify-center items-center p-8 text-red-600">
      <p className="mb-4 font-bold text-xl">Error: {error}</p>
      <Link href="/dashboard/candidate"><a className="text-blue-600 underline">Back to Dashboard</a></Link>
    </div>
  )
  return (
    <div className="p-8 max-w-4xl mx-auto bg-white rounded-xl shadow-lg">
      <Link href={`/dashboard/candidate/interests/${params.id}`}>
        <button className="mb-6 text-blue-600 hover:underline flex items-center gap-2"><ArrowLeft className="w-5 h-5"/> Back to Opportunity</button>
      </Link>
      <h1 className="text-3xl font-bold mb-6">{interest.jobs.title} - Sign RTR</h1>
      <iframe src={interest.right_to_represent_url} title="RTR Doc" className="w-full h-96 rounded border mb-8"></iframe>

      <div>
        <canvas ref={canvasRef} className="w-full h-36 border border-gray-400 bg-white rounded cursor-crosshair"
          onPointerDown={startDrawing} onPointerMove={draw} onPointerCancel={stopDrawing} onPointerUp={stopDrawing} onPointerLeave={stopDrawing} />
        <div className="flex gap-3 mt-4">
          <button onClick={clearCanvas} className="flex-1 py-3 rounded bg-gray-200 hover:bg-gray-300 font-semibold">Clear Signature</button>
          <button
            onClick={submitSignature}
            disabled={signing || !hasSignature}
            className="flex-1 py-3 rounded bg-blue-600 hover:bg-blue-700 text-white font-semibold disabled:opacity-60">
            {signing ? "Signing..." : "Sign & Submit"}
          </button>
        </div>
        <p className="mt-3 text-sm text-gray-600 italic">Signing electronically confirms your agreement as legally binding.</p>
      </div>
    </div>
  )
}

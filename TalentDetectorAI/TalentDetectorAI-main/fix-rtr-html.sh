#!/bin/bash
# fix-rtr-html.sh
set -e

echo "🛠️ Patching RTR generator to output professional HTML..."

cat > app/api/generate-rtr-auto/route.ts << 'END_RTR'
import { createClient } from '@supabase/supabase-js'
import { NextResponse } from 'next/server'

export const dynamic = 'force-dynamic'

export async function POST(request: Request) {
  try {
    const { interestId } = await request.json()
    if (!interestId) return NextResponse.json({ error: 'interestId required' }, { status: 400 })

    const supabaseAdmin = createClient(
      process.env.NEXT_PUBLIC_SUPABASE_URL!,
      process.env.SUPABASE_SERVICE_ROLE_KEY!
    )

    const { data: interest, error } = await supabaseAdmin
      .from('candidate_interests')
      .select(`
        *,
        candidates(id, name, email, phone, location, user_id),
        jobs(id, title, location, salary_min, salary_max),
        profiles!candidate_interests_agency_id_fkey(id, full_name, company, email)
      `)
      .eq('id', interestId)
      .single()

    if (error || !interest) return NextResponse.json({ error: 'Interest not found' }, { status: 404 })

    const { candidates: candidate, jobs: job, profiles: agency } = interest

    const html = `
<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8"/>
<title>Right to Represent Agreement</title>
<style>
body { font-family: 'Segoe UI', Arial, sans-serif; background: #f4f6fb; color: #1e293b; margin:0;padding:0;}
.container{max-width:700px;margin:40px auto 0 auto;background:#fff;padding:40px 32px 32px 32px;border-radius:10px;box-shadow:0 3px 15px #6b728030;}
h1{color:#1d4ed8;}
.section{margin-bottom:34px;}
.section-title{margin-bottom:8px;font-weight:600;color:#6d28d9;letter-spacing:.06em;}
dl{display:grid;grid-template-columns:150px 1fr;row-gap:7px;}
dt{font-weight:bold;}
ul{padding-left:18px;margin-bottom:12px;}
.signature-area{margin-top:1.5rem; border-bottom:2px solid #444; height:40px;}
.footer{text-align:center;margin-top:35px;color:#6b7280;font-size:.92em;}
</style>
</head>
<body>
<div class="container">
  <h1>Right to Represent Agreement</h1>
  <p><em>Generated: ${new Date().toLocaleString()}</em></p>
  <div class="section">
    <span class="section-title">Parties</span>
    <dl>
      <dt>Agency:</dt><dd>${agency?.full_name || 'N/A'} (${agency?.company || 'N/A'})</dd>
      <dt>Agency Email:</dt><dd>${agency?.email || 'N/A'}</dd>
      <dt>Candidate:</dt><dd>${candidate?.name || 'N/A'}</dd>
      <dt>Candidate Email:</dt><dd>${candidate?.email || 'N/A'}</dd>
      <dt>Candidate Phone:</dt><dd>${candidate?.phone || 'N/A'}</dd>
      <dt>Candidate Location:</dt><dd>${candidate?.location || 'N/A'}</dd>
    </dl>
  </div>
  <div class="section">
    <span class="section-title">Position</span>
    <dl>
      <dt>Title:</dt><dd>${job?.title || ''}</dd>
      <dt>Location:</dt><dd>${job?.location || ''}</dd>
      <dt>Salary:</dt><dd>£${job?.salary_min?.toLocaleString() || '0'} - £${job?.salary_max?.toLocaleString() || '0'}</dd>
    </dl>
  </div>
  <div class="section">
    <span class="section-title">Agreement Terms</span>
    <ul>
      <li>Exclusive right to represent candidate for 90 days.</li>
      <li>Agency may submit candidate’s CV and act as main contact.</li>
      <li>Candidate must not apply directly to company during this period.</li>
      <li>Candidate agrees to provide accurate info and timely responses.</li>
      <li>Agency acts professionally, maintains confidentiality, provides progress updates.</li>
      <li>No fee for candidate; agency paid by company.</li>
      <li>Electronic signature is legally binding.</li>
    </ul>
  </div>
  <p><strong>Candidate Signature:</strong></p>
  <div class="signature-area"></div>
  <p><strong>Date:</strong></p>
  <div class="signature-area"></div>
  <div class="footer">
    Generated by TalentDetector AI &copy; ${new Date().getFullYear()}
  </div>
</div>
</body>
</html>
`.trim();

    const fileName = `rtr_${interestId}_${Date.now()}.html`
    const { error: uploadError } = await supabaseAdmin.storage
      .from('documents')
      .upload(fileName, html, { contentType: 'text/html', upsert: false })

    if (uploadError) return NextResponse.json({ error: uploadError.message }, { status: 500 })

    const { data: { publicUrl } } = supabaseAdmin.storage.from('documents').getPublicUrl(fileName)

    await supabaseAdmin.from('candidate_interests').update({
      right_to_represent_url: publicUrl,
      agency_notes: `RTR generated ${new Date().toISOString()}`
    }).eq('id', interestId)

    if (candidate?.user_id) {
      await supabaseAdmin.from('notifications').insert({
        user_id: candidate.user_id,
        type: 'rtr_ready_signature',
        title: 'Please sign your Right to Represent Agreement',
        message: `Your RTR for ${job?.title} is ready.`,
        link: `/dashboard/candidate/interests/${interestId}/sign-rtr`,
        ai_priority: 'high',
        metadata: { interest_id: interestId }
      })
    }

    return NextResponse.json({ success:true, rtr_url: publicUrl })
  } catch (error) {
    return NextResponse.json({ error: error.message || 'Error generating RTR' }, { status:500 })
  }
}
END_RTR

echo "✅ RTR API now generates modern HTML with no weird chars."
echo "Restart your dev server: npm run dev"

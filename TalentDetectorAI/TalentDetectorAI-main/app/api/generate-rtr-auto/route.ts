import { createClient } from '@supabase/supabase-js'
import { NextResponse } from 'next/server'

export const dynamic = 'force-dynamic'
export const maxDuration = 30

function generateRTRContent(interest: any, candidate: any, job: any, agency: any): string {
  return `
==============================================================
                 RIGHT TO REPRESENT AGREEMENT
                 Powered by TalentDetector AI
==============================================================

Document ID: ${interest.id}
Generated: ${new Date().toLocaleString('en-GB', { timeZone: 'UTC' })}
AI Match Score: ${interest.ai_match_score ?? 'N/A'}%

==============================================================
PARTIES

Recruitment Agency
  Name      : ${agency.full_name}
  Company   : ${agency.company || 'Not specified'}
  Email     : ${agency.email}
  Phone     : ${agency.phone || 'Not specified'}

Candidate
  Name      : ${candidate.name}
  Email     : ${candidate.email}
  Phone     : ${candidate.phone || 'Not specified'}
  Location  : ${candidate.location || 'Not specified'}

Position
  Title     : ${job.title}
  Location  : ${job.location}
  Type      : ${job.employment_type || 'Not specified'}
  Salary    : £${job.salary_min?.toLocaleString()} - £${job.salary_max?.toLocaleString()}

==============================================================
TERMS AND CONDITIONS

1. EXCLUSIVE REPRESENTATION
   The Recruitment Agency ("Agency") shall have the exclusive right to
   represent the Candidate for the above-specified position for a period
   of 12 months from the date of this agreement.

2. CANDIDATE CONSENT
   The Candidate hereby grants the Agency permission to:
   - Submit their CV and application materials to the hiring company
   - Represent them in negotiations regarding this position
   - Act as the primary point of contact with the employer

3. CONFIDENTIALITY
   Both parties agree to maintain confidentiality of all information
   shared during the recruitment process, except as required by law or
   with explicit written consent.

4. CANDIDATE OBLIGATIONS
   The Candidate agrees to:
   - Not apply directly to the company for this position
   - Not engage with other agencies for this specific role
   - Promptly respond to communications from the Agency
   - Provide accurate and truthful information

5. AGENCY OBLIGATIONS
   The Agency agrees to:
   - Act in the Candidate's best interests
   - Maintain professional standards
   - Keep the Candidate informed of application progress
   - Protect the Candidate's personal information

6. TERMINATION
   Either party may terminate this agreement with 7 days' written notice,
   except where the Candidate's application is already under active
   consideration by the employer.

7. FEES
   The Candidate shall not be liable for any fees. All recruitment fees
   are the responsibility of the hiring company.

==============================================================
CANDIDATE ACKNOWLEDGMENT

By signing this agreement electronically, I acknowledge that:
- I have read and understood all terms and conditions
- I consent to the Agency representing me for this position
- All information provided is accurate and complete
- I agree to the exclusive representation terms outlined above

==============================================================
DIGITAL SIGNATURE

Candidate Signature: _________________________________
                     (To be completed electronically)

Date: _________________________________

==============================================================
                    END OF AGREEMENT
==============================================================

This document is legally binding when signed electronically by the Candidate.
For questions or concerns, please contact the Agency using the details above.

Generated by TalentDetector AI - Intelligent Recruitment Platform
`.trim()
}

export async function POST(request: Request) {
  try {
    const { interestId } = await request.json()
    if (!interestId) {
      return NextResponse.json({ error: 'Interest ID required' }, { status: 400 })
    }

    const supabaseAdmin = createClient(
      process.env.NEXT_PUBLIC_SUPABASE_URL!,
      process.env.SUPABASE_SERVICE_ROLE_KEY!,
      { auth: { autoRefreshToken: false, persistSession: false } }
    )

    // Fetch interest with all related data
    const { data: interest, error: fetchError } = await supabaseAdmin
      .from('candidate_interests')
      .select(`
        *,
        candidates(id, name, email, phone, location, user_id),
        jobs(id, title, location, salary_min, salary_max, employment_type),
        profiles!candidate_interests_agency_id_fkey(id, full_name, company, email, phone)
      `)
      .eq('id', interestId)
      .single()

    if (fetchError || !interest) {
      console.error('Fetch error:', fetchError)
      throw new Error(`Interest not found: ${fetchError?.message || ''}`)
    }

    const candidate = interest.candidates
    const job = interest.jobs
    const agency = interest.profiles

    // Validate that we have all required data
    if (!candidate || !job || !agency) {
      throw new Error('Missing required data: candidate, job, or agency information')
    }

    // Generate RTR content
    const rtrContent = generateRTRContent(interest, candidate, job, agency)

    // Upload to storage
    const fileName = `rtr/${interestId}.txt`
    const { error: uploadError } = await supabaseAdmin.storage
      .from('documents')
      .upload(fileName, rtrContent, { 
        contentType: 'text/plain', 
        upsert: true, 
        cacheControl: '0' 
      })
    
    if (uploadError) {
      console.error('Upload error:', uploadError)
      throw new Error(`Upload failed: ${uploadError.message}`)
    }

    // Get public URL
    const { data: { publicUrl } } = supabaseAdmin.storage
      .from('documents')
      .getPublicUrl(fileName)

    // Update candidate_interests - KEEP EXISTING STATUS, don't change it to rtr_ready
    const { error: updateError } = await supabaseAdmin
      .from('candidate_interests')
      .update({
        right_to_represent_url: publicUrl,
        right_to_represent_signed: false,  // Reset signature status
        agency_notes: `RTR (re)generated on ${new Date().toISOString()}`
        // ✅ REMOVED: status: 'rtr_ready' - this was causing the constraint violation
      })
      .eq('id', interestId)
    
    if (updateError) {
      console.error('Update error:', updateError)
      throw new Error(`Update failed: ${updateError.message}`)
    }

    // Send notifications
    await Promise.all([
      candidate?.user_id &&
        supabaseAdmin.from('notifications').insert({
          user_id: candidate.user_id,
          type: 'rtr_ready',
          title: '✍️ RTR ready to sign',
          message: `Your Right-to-Represent agreement for "${job.title}" is ready (or has been updated) and awaits your signature.`,
          link: `/dashboard/candidate/interests/${interestId}/sign-rtr`,
          ai_priority: 'high',
          metadata: { interest_id: interestId, job_title: job.title, regenerated: true }
        }),
      supabaseAdmin.from('notifications').insert({
        user_id: interest.agency_id,
        type: 'rtr_generated',
        title: '📄 RTR (re)generated',
        message: `RTR for ${candidate.name} on "${job.title}" has been (re)generated and sent to the candidate.`,
        link: `/dashboard/agency/interests/${interestId}`,
        ai_priority: 'normal',
        metadata: { interest_id: interestId, candidate_name: candidate.name, regenerated: true }
      })
    ])

    return NextResponse.json({ 
      success: true, 
      rtr_url: publicUrl,
      message: 'RTR generated successfully and sent to candidate'
    })
  } catch (err: any) {
    console.error('RTR generation error:', err)
    return NextResponse.json({ 
      error: err?.message || 'RTR generation failed' 
    }, { status: 500 })
  }
}
